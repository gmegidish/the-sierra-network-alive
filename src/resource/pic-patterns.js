const TEXTURE_BYTES = [
  0x04, 0x29, 0x40, 0x24, 0x09, 0x41, 0x25, 0x45,
  0x41, 0x90, 0x50, 0x44, 0x48, 0x08, 0x42, 0x28,
  0x89, 0x52, 0x89, 0x88, 0x10, 0x48, 0xa4, 0x08,
  0x44, 0x15, 0x28, 0x24, 0x00, 0x0a, 0x24, 0x20,
];
// The original ignores the very last bit, so the cycle is 255 bits long.
const TEXTURE_CYCLE_BITS = 255;

function expandTextureBits() {
  const bits = TEXTURE_BYTES.flatMap((byte) => [0, 1, 2, 3, 4, 5, 6, 7].map((bit) => (byte >> bit) & 1));
  const cycle = bits.slice(0, TEXTURE_CYCLE_BITS);
  // Duplicated so readers can run past the end without wrapping (as ScummVM does).
  return Uint8Array.from([...cycle, ...cycle]);
}

export const PATTERN_TEXTURE_BITS = expandTextureBits();

